#!/usr/bin/env python3
"""Turn `fnox list` output into a relay fnox.toml (names only, never values).

  { fnox list; echo "== production"; fnox list -P production --no-defaults; } \
    | fnox-to-relay.py --project shop --env qa --org infra > fnox.toml

stdin: the `fnox list` table (default profile); an optional line starting with `== production`
then the production-only table. A key is the first [A-Z_][A-Z0-9_]* token on a table row that is
not the header `KEY`; the value column is never copied. Item names: lowercase, `_` -> `-`, drop
a leading `<project>-`, append `-<project>-<env>` (SHOP_PGPASSWORD -> pgpassword-shop-qa).

Multi-line values (PEM keys) live in the item's Notes and must be referenced as `<item>/notes`.
`fnox list` cannot tell, so name those keys: `--notes KEY,KEY`, or `--run-log` with a migration
log whose `ok` lines end in `(notes)` for them. Every secret gets `if_missing = "error"`, so a
missing item stops `fnox exec` instead of leaving a variable empty.
"""
import argparse
import datetime
import json
import os
import re
import sys

KEY_RE = re.compile(r"^[A-Z_][A-Z0-9_]*$")
PROJECT_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
MARKER = "== production"
ENVS = ("dev", "qa", "prod")
LOG_NOTES_RE = re.compile(r"^ok\s+([A-Za-z_][A-Za-z0-9_]*) -> .*\(notes\)\s*$")


def item_name(key, project, env):
    p = project
    k = key.lower().replace("_", "-")
    if k.startswith(p + "-"):
        k = k[len(p) + 1:]
    return f"{k}-{p}-{env}"


def parse(text):
    """Return (default_keys, production_keys), each in first-seen order without duplicates."""
    default, prod = [], []
    cur = default
    for line in text.splitlines():
        if line.startswith(MARKER):
            cur = prod
            continue
        fields = re.sub(r"[│┃|]", " ", line).split()
        if fields and KEY_RE.match(fields[0]) and fields[0] != "KEY" and fields[0] not in cur:
            cur.append(fields[0])
    return default, prod


def notes_keys_from_log(text):
    """Keys the migration run log stored in Notes (`ok    KEY -> ... as 'name' (notes)`)."""
    return {m.group(1) for m in map(LOG_NOTES_RE.match, text.splitlines()) if m}


def ref(key, project, env, notes):
    name = item_name(key, project, env)
    return name + "/notes" if key in notes else name


def render(default, prod, project, env, prod_env, org, relay_url, notes=frozenset()):
    q = json.dumps
    out = [
        "# Generated by relay/tools/fnox-to-relay.py on %s." % datetime.date.today().isoformat(),
        "# Names only: every value lives in Vaultwarden and is read through the broker.",
        "",
        "[providers.relay]",
        'type = "vault"',
        "address = %s" % q(f"{relay_url.rstrip('/')}/{org}"),
        "path = %s" % q(project),
        'token = "tailscale"',
        "",
        "[secrets]",
    ]
    def line(k, e):
        return f'{k} = {{ provider = "relay", value = {q(ref(k, project, e, notes))}, if_missing = "error" }}'
    out += [line(k, env) for k in default]
    if prod:
        out += ["", "[profiles.production.secrets]"]
        out += [line(k, prod_env) for k in prod]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--project", required=True)
    ap.add_argument("--env", required=True, help="environment of the default profile (dev|qa|prod)")
    ap.add_argument("--org", required=True, choices=["local", "infra"])
    ap.add_argument("--prod-env", default="prod")
    ap.add_argument("--relay-url", default=os.environ.get("RELAY_URL") or "https://broker.example.ts.net",
                    help="broker URL (default: $RELAY_URL)")
    ap.add_argument("--notes", default="", help="KEY,KEY whose values are in the item's Notes")
    ap.add_argument("--run-log", help="migration run log: keys logged as (notes) are Notes")
    a = ap.parse_args(argv)

    def err(msg):
        print(f"error: {msg}", file=sys.stderr)
        return 2
    if not PROJECT_RE.match(a.project):
        return err("project must be lowercase kebab-case")
    for opt, v in (("--env", a.env), ("--prod-env", a.prod_env)):
        if v not in ENVS:
            return err(f"{opt} must be one of {'|'.join(ENVS)}")
    notes = {k.strip() for k in a.notes.split(",") if k.strip()}
    bad = sorted(k for k in notes if not KEY_RE.match(k))
    if bad:
        return err(f"--notes: not a key: {', '.join(bad)}")
    default, prod = parse(sys.stdin.read())
    if not default and not prod:
        return err("no keys found on stdin (expected `fnox list` output)")
    unknown = sorted(notes - set(default) - set(prod))
    if unknown:
        return err(f"--notes: not in the fnox list input: {', '.join(unknown)}")
    if a.run_log:
        try:
            with open(a.run_log) as f:
                notes |= notes_keys_from_log(f.read()) & (set(default) | set(prod))
        except OSError as e:
            return err(f"cannot read --run-log ({type(e).__name__})")
    sys.stdout.write(render(default, prod, a.project, a.env, a.prod_env, a.org, a.relay_url, notes))
    return 0


if __name__ == "__main__":
    sys.exit(main())
