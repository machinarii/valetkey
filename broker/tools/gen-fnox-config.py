#!/usr/bin/python3 -I
"""Generate the fnox config for one org's [api.*] routes (references only, never values).

  gen-fnox-config.py --routes /etc/valetkey-broker/routes.toml --org infra --org-id <id> > api.toml

Run by valetkey-broker routes on the broker; the output is /var/lib/valetkey-broker-<org>/api.toml, read by
`fnox proxy run` in valetkey-broker-<org>.service. Each route becomes one secret (env = false: the broker
never sees it) and one strict proxy rule that swaps the route's placeholder for the real value,
only for that upstream host, those methods and paths.
"""
import argparse
import json
import os
import re
import sys
import urllib.parse

# brokerlib sits next to this file on the broker (/usr/local/libexec/valetkey-broker/) and one level up in
# the repo (broker/tools/ beside broker/brokerlib/); -I keeps both off sys.path otherwise.
_here = os.path.dirname(os.path.abspath(__file__))
for _d in (_here, os.path.dirname(_here)):
    if os.path.isdir(os.path.join(_d, "brokerlib")):
        sys.path.insert(0, _d)
        break
from brokerlib.routes import load_routes  # noqa: E402

q = json.dumps  # TOML basic strings accept JSON string syntax for these names


def env_name(route):
    return "BROKER_API_" + re.sub(r"[^A-Z0-9]", "_", route.upper())


def placeholder(route):
    return f"fnox-ph-{route}-not-a-secret"  # must match broker_read.placeholder


def generate(routes, org, org_id, collection_id=None):
    """fnox TOML for `org`'s api routes. `collection_id` None: provider scoped by org only."""
    api = routes.for_org(org).api
    out = [
        f"# Generated by gen-fnox-config.py from routes.toml for org {q(org)}. Do not edit;\n",
        "# run `sudo valetkey-broker routes install` instead. References only, never values.\n",
        "# [providers.vw] sets organization_id only: items in collections nested under the\n",
        "# broker collection are in the org but not in the parent collection, so a `collection`\n",
        "# filter would hide them. The account sees only its own collections anyway.\n",
        '# if_missing = "warn": one missing api item must not stop the whole read service from\n',
        "# starting; `sudo valetkey-broker check <org>` reports it. With no [[proxy.rules]] at all,\n",
        "# with-bw-session runs the broker without `fnox proxy run`.\n",
        "root = true\n\n",
        "[providers.vw]\n",
        'type = "bitwarden"\n',
        f"organization_id = {q(org_id)}\n",
    ]
    if collection_id:
        out.append(f"collection = {q(collection_id)}\n")
    out.append("\n[secrets]\n")
    rules = []
    for name in sorted(api):
        r = api[name]
        key = env_name(name)
        upstream = urllib.parse.urlsplit(r.upstream)
        paths = []
        for endpoint in r.paths:
            path = upstream.path.rstrip("/") + endpoint
            if not path.endswith("/"):
                paths.append(path)
            if not r.model:
                paths.append(path.rstrip("/") + "/**")
        out.append(f'{key} = {{ provider = "vw", value = {q(r.item)}, env = false, '
                   f'if_missing = "warn" }}\n')
        rules.append(
            f"\n[[proxy.rules]]\nsecret = {q(key)}\ndomain = {q(upstream.hostname)}\nheader = {q(r.auth_header.lower())}\n"
            f"methods = {q(r.methods)}\npaths = {q(paths)}\n"
            f"placeholder = {q(placeholder(name))}\n")
    out.append('\n[proxy]\negress = "strict"\naudit = true\n')
    out += rules
    return "".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(prog="gen-fnox-config.py")
    ap.add_argument("--routes", required=True)
    ap.add_argument("--org", required=True, choices=("local", "infra"))
    ap.add_argument("--org-id", required=True)
    ap.add_argument("--collection-id", help="optional; omit to scope by organization only")
    args = ap.parse_args(argv)
    sys.stdout.write(generate(load_routes(args.routes), args.org, args.org_id, args.collection_id))


if __name__ == "__main__":
    main()
